#!/usr/bin/env python3
"""Render the guided Ubuntu Desktop installer profile with reviewed Git revisions."""
import argparse
import json
from pathlib import Path
import re

WORKSTATION_URL = 'https://github.com/jamwujustyle/workstation-setup.git'
PLAYBOOK_URL = 'https://github.com/jamwujustyle/agent-playbook.git'


def render(repo, revision, playbook_revision):
    for name, value in [('workstation', revision), ('playbook', playbook_revision)]:
        if not re.fullmatch(r'[0-9a-f]{40}', value):
            raise ValueError(f'{name} revision must be a full lowercase Git commit hash')
    packages = {'git', 'python3', 'ca-certificates'}
    for group in ['cli', 'desktop']:
        for line in (repo / 'packages' / f'{group}.txt').read_text().splitlines():
            name = line.strip()
            if not name or name.startswith('#'):
                continue
            if not re.fullmatch(r'[a-z0-9][a-z0-9+.-]*', name):
                raise ValueError(f'Invalid package name in {group} manifest')
            packages.add(name)
    # Argument arrays avoid shell interpolation. Use HTTPS: a new machine has no SSH key.
    commands = []
    # Explicit umask keeps the public source pools readable at the user's first login.
    git_prefix = ['curtin', 'in-target', '--target=/target', '--', 'env',
                  'GIT_TERMINAL_PROMPT=0', 'sh', '-c', 'umask 022; exec "$@"',
                  'workstation-fetch', 'git']
    for url, destination, commit in [
        (WORKSTATION_URL, '/opt/workstation-setup', revision),
        (PLAYBOOK_URL, '/opt/agent-playbook', playbook_revision),
    ]:
        commands.extend([
            git_prefix + ['clone', '--no-checkout', '--single-branch', url, destination],
            git_prefix + ['-C', destination, 'checkout', '--detach', commit],
        ])
    commands.append(['curtin', 'in-target', '--target=/target', '--', '/usr/bin/python3', '/opt/workstation-setup/installer/stage.py', '--apply'])
    lines = [
        '#cloud-config',
        '# Guided Ubuntu Desktop 24.04 LTS installation with workstation provisioning.',
        '# Keep disk, encryption, account, and other interactive installer choices.',
        '# No disk layout, username, password, or private key is stored here.',
        '# Generated by installer/render_autoinstall.py; update the generator/manifests.',
        'autoinstall:',
        '  version: 1',
        '  interactive-sections:',
        "    - '*'",
        '  packages:',
    ]
    lines.extend('    - ' + package for package in sorted(packages))
    lines.append('  late-commands:')
    lines.extend('    - ' + json.dumps(command) for command in commands)
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--revision', required=True, help='Reviewed workstation source commit')
    parser.add_argument('--playbook-revision', required=True, help='Reviewed agent-playbook commit')
    args = parser.parse_args()
    try:
        print(render(Path(__file__).resolve().parents[1], args.revision, args.playbook_revision), end='')
    except ValueError as error:
        parser.error(str(error))


if __name__ == '__main__':
    main()
